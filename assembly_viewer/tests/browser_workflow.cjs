/* Usage: node browser_workflow.cjs URL TRACE_DIR OFFLINE_HTML */
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const assert = require('node:assert/strict');
const {pathToFileURL}=require('node:url');
(async()=>{
  const [url,trace,offline]=process.argv.slice(2);
  const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url);
  await page.waitForFunction(()=>document.querySelector('#nodes-path').value.includes('YM-3'));
  assert.equal(await page.locator('svg').count(),1);
  assert.equal(await page.locator('iframe').count(),0);
  await page.click('#read');
  await page.waitForFunction(()=>!document.querySelector('#start').disabled);
  assert.equal(await page.locator('body').getAttribute('data-event'),'input.ready');
  assert.equal(await page.locator('#molecule-svg .node').count(),7);
  const proportion=await page.locator('#molecule-svg .node').first().evaluate(n=>Number(n.querySelector('text').getAttribute('font-size'))/(2*Number(n.querySelector('circle').getAttribute('r'))));
  assert.ok(Math.abs(proportion-.46)<1e-10);
  assert.match(await page.locator('#caption').textContent(),/7 个输入节点/);
  assert.equal(await page.locator('#molecule-svg .node[data-gid="0"]').count(),1);
  await page.click('#molecule-svg .node[data-gid="0"]');
  assert.match(await page.locator('#node-detail').textContent(),/"GID": 0/);
  const originalPath=await page.locator('#nodes-path').inputValue();
  await page.fill('#nodes-path',originalPath+'.changed');
  assert.ok(await page.locator('#start').isDisabled());
  await page.fill('#nodes-path',originalPath);
  assert.ok(await page.locator('#start').isEnabled());
  const before=await (await page.request.get(url+'/api/runs')).json();
  assert.equal(before.runs[0].status,'ready');
  const run=before.runs[0].id;
  const prepared=await (await page.request.get(url+`/api/trace/events?run=${run}&mode=live`)).json();
  assert.equal(prepared.events.filter(e=>e.kind.startsWith('search.')).length,0);
  await page.evaluate(()=>{window.framesSeen=[];document.addEventListener('assembly-frame',e=>window.framesSeen.push(e.detail));});
  await page.selectOption('#speed','40');
  await page.click('#start');
  await page.waitForFunction(()=>document.body.dataset.event==='run.finished',{},{timeout:20000}).catch(async e=>{console.error(await page.evaluate(()=>({event:document.body.dataset.event,message:document.querySelector('#message').textContent,position:document.querySelector('#position').textContent,play:document.querySelector('#play').textContent,frames:window.framesSeen})));throw e;});
  assert.ok(!(await page.locator('#node-detail').textContent()).includes('未组装'));
  const frames=await page.evaluate(()=>window.framesSeen);
  assert.ok(frames.some(e=>e.kind==='search.visit'));
  const firstVisit=frames.find(e=>e.kind==='search.visit');
  assert.ok(frames.some(e=>e.kind==='search.selected'&&e.round_id===firstVisit.round_id&&e.seq>firstVisit.seq));
  const durable=await (await page.request.get(url+`/api/trace/events?run=${run}&mode=live&limit=1000`)).json();
  assert.deepEqual(frames.map(e=>e.seq),durable.events.filter(e=>e.seq>prepared.events.at(-1).seq).map(e=>e.seq));
  await page.click('#phases button[data-phase="side"]');
  await page.check('#stage-only');
  await page.click('#phases button[data-phase="side"]');
  await page.waitForFunction(()=>document.querySelector('#canvas-title').textContent.includes('侧链 · 阶段起点'));
  await page.click('#play');
  await page.waitForFunction(()=>document.querySelector('#play').textContent==='播放',{},{timeout:10000});
  assert.equal(await page.locator('body').getAttribute('data-event'),'stage.complete');
  await page.click('#export');
  await page.waitForSelector('#exports a');
  await page.waitForSelector('#exports a[href$="/svg"]');
  await page.waitForSelector('#exports a[href$="/pdf"]');
  await page.screenshot({path:'/tmp/viewer-single-canvas.png',fullPage:true});

  // Import all-stage synthetic data, then seek by persisted stage index.
  await page.fill('#open-path',trace);
  await page.click('#open-trace');
  await page.waitForFunction(()=>!document.querySelector('#sample-note').hidden);
  assert.match(await page.locator('#molecule-svg').textContent(),/SU26/);
  assert.equal(await page.locator('#phases button').count(),6);
  await page.selectOption('#mode','formal');
  await page.click('#phases button[data-phase="flex"]');
  await page.waitForFunction(()=>document.querySelector('#canvas-title').textContent.includes('柔性连接 · 阶段起点'));
  assert.match(await page.locator('#canvas-title').textContent(),/柔性连接.*阶段起点/);
  await page.click('#play');
  await page.waitForFunction(()=>document.querySelector('#play').textContent==='播放',{},{timeout:10000});
  assert.equal(await page.locator('body').getAttribute('data-event'),'stage.complete');

  const offlinePage=await browser.newPage({viewport:{width:1440,height:1000}});
  offlinePage.on('pageerror',e=>errors.push(e.message));
  await offlinePage.goto(pathToFileURL(offline).href);
  await offlinePage.waitForFunction(()=>document.body.dataset.event==='input.ready');
  assert.equal(await offlinePage.locator('svg').count(),1);
  await offlinePage.check('#stage-only');
  await offlinePage.click('#phases button[data-phase="side"]');
  await offlinePage.waitForFunction(()=>document.querySelector('#canvas-title').textContent.includes('侧链 · 阶段起点'));
  await offlinePage.selectOption('#speed','40');
  await offlinePage.click('#play');
  await offlinePage.waitForFunction(()=>document.querySelector('#play').textContent==='播放',{},{timeout:10000});
  assert.equal(await offlinePage.locator('body').getAttribute('data-event'),'stage.complete');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser workflow: preview/start, exact event order, all-stage replay and offline playback passed');
})().catch(e=>{console.error(e);process.exit(1);});
